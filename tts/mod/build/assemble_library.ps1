# build/assemble_library.ps1
# Validate each faction JSON, concatenate into one library array, and emit both
#   src/data/unit_library.json  (external / HTML Card Forge)
#   src/data/unit_library.lua   (embedded JSON string the TTS mod decodes)
$ErrorActionPreference = "Stop"
$root    = Split-Path -Parent $PSScriptRoot
$facDir  = Join-Path $root "src\data\factions"
$order   = @("MIL","GOB","STW","ORK","SAU")

$factions = @()
$totalUnits = 0
foreach ($p in $order) {
    $file = Join-Path $facDir "$p.json"
    if (-not (Test-Path $file)) { Write-Host "MISSING: $p.json"; continue }
    # -Encoding UTF8 is REQUIRED. The faction JSONs carry no BOM, and PowerShell
    # 5.1's Get-Content falls back to the ANSI codepage without one — which
    # turns every UTF-8 middle dot (C2 B7) into "Â·", then Set-Content writes
    # that back out as UTF-8 and the corruption is baked in. That is exactly how
    # unit_library.lua ended up full of mojibake.
    $raw = Get-Content -LiteralPath $file -Raw -Encoding UTF8
    try { $obj = $raw | ConvertFrom-Json } catch { Write-Host "INVALID JSON: $p.json -> $($_.Exception.Message)"; exit 1 }
    $u = @($obj.units).Count
    $cav = @($obj.units | Where-Object { $_.base.class -eq "Cavalry" }).Count
    $mon = @($obj.units | Where-Object { $_.base.class -eq "Large" -or $_.base.class -eq "Monstrous" }).Count
    Write-Host ("{0}: {1} units  (cavalry {2}, monster {3})" -f $obj.faction, $u, $cav, $mon)
    $totalUnits += $u
    $factions += $obj
}

# Build the combined JSON array (compact but valid).
$combined = $factions | ConvertTo-Json -Depth 40 -Compress

# unit_library.json (pretty for humans / the HTML forge)
$pretty = $factions | ConvertTo-Json -Depth 40
Set-Content -LiteralPath (Join-Path $root "src\data\unit_library.json") -Value $pretty -Encoding UTF8

# unit_library.lua (embedded JSON string the mod JSON.decodes)
$h1 = "-- data/unit_library.lua  (GENERATED by build/assemble_library.ps1 - do not hand-edit)"
$h2 = "-- Full 5-faction unit catalog as a JSON string the mod decodes into CUS.UNIT_LIBRARY."
$lua = $h1 + "`r`n" + $h2 + "`r`n" + "CUS = CUS or {}`r`n" +
       "CUS.UNIT_LIBRARY_JSON = [==[`r`n" + $combined + "`r`n]==]`r`n"
Set-Content -LiteralPath (Join-Path $root "src\data\unit_library.lua") -Value $lua -Encoding UTF8

Write-Host ("--- assembled {0} factions, {1} units ---" -f $factions.Count, $totalUnits)
